import { projectKey, seedId } from './deterministic-ids.js';
import type { SeedProject } from './render-dump.js';

/**
 * Renders `packages/web/src/data/sample-projects.ts`, the web's sample-project constant (DIS-92
 * design D3; several projects, DIS-32 design D4), from the same rows as the seed: one object per
 * project in name order (code-unit order, whatever the order of `projects`), each with the project id
 * `renderSeedDump` writes and the counts of its rows. The text depends only on the rows, never on
 * their order; LF line endings and a final line feed.
 *
 * @param projects The projects of the seed with their exported rows, in any order.
 * @returns The file content.
 */
export function renderSampleProjects(projects: readonly SeedProject[]): string {
  const objects = [...projects]
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .flatMap(({ name, rows }) => [
      '  {',
      `    id: ${tsString(seedId(projectKey(name)))},`,
      `    name: ${tsString(name)},`,
      `    language: ${tsString(rows.project.language)},`,
      `    framework: ${rows.project.framework === null ? 'null' : tsString(rows.project.framework)},`,
      `    fileCount: ${rows.files.length},`,
      `    symbolCount: ${rows.symbols.length},`,
      `    edgeCount: ${rows.edges.length},`,
      `    commitCount: ${rows.commits.length},`,
      '  },',
    ]);
  const lines = [
    '// Generated by `npm run seed:build`; do not edit by hand.',
    '',
    'export const SAMPLE_PROJECTS = [',
    ...objects,
    '] as const;',
  ];
  return `${lines.join('\n')}\n`;
}

/** A single-quoted TypeScript string literal, with `\` and `'` escaped. */
function tsString(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}
